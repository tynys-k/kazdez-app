// Копия КП для постоянной фирмы: та же структура и текст, новая дата,
// номер выдаст база. Статус сбрасывается в черновик — иначе копия
// мгновенно попала бы в статистику как отправленная.
export function duplicateProposal(proposal, today = new Date().toLocaleDateString("en-CA")) {
  const copy = { ...proposal };
  delete copy.id;
  delete copy.number;
  delete copy.seq;
  delete copy.year;
  delete copy.request_id;
  delete copy.created_at;
  delete copy.updated_at;
  return {
    ...copy,
    issue_date: today,
    status: "draft",
    sent_at: null,
    decided_at: null,
    decline_reason: null,
    items: (proposal.items || []).map((item) => blankItem({ ...item, id: undefined })),
  };
}

// Воронка КП: сколько ушло клиенту и сколько из этого согласовано.
// Черновики в знаменатель не идут — неотправленное КП ни о чём не говорит.
export function proposalFunnel(proposals = []) {
  const sent = proposals.filter((p) => p.status !== "draft");
  const accepted = sent.filter((p) => p.status === "accepted");
  return {
    total: proposals.length,
    drafts: proposals.filter((p) => p.status === "draft").length,
    sent: sent.length,
    accepted: accepted.length,
    declined: sent.filter((p) => p.status === "declined").length,
    waiting: sent.filter((p) => p.status === "sent").length,
    acceptedAmount: accepted.reduce((sum, p) => sum + (Number(p.total) || 0), 0),
    sentAmount: sent.reduce((sum, p) => sum + (Number(p.total) || 0), 0),
    conversion: sent.length ? Math.round((accepted.length / sent.length) * 100) : 0,
  };
}

// Что мешает отправить КП. Список показывается в форме: пустая таблица
// стоимости или безымянный заказчик — самые частые причины, по которым
// КП приходилось переделывать после отправки.
export function proposalIssues(draft = {}) {
  const issues = [];
  const items = draft.items || [];
  if (!String(draft.subject || "").trim()) issues.push("Не указана услуга в заголовке КП.");
  if (!items.length) issues.push("В таблице стоимости нет ни одной строки.");
  if (items.some((item) => !String(item.name || "").trim())) issues.push("У строки стоимости нет названия услуги.");
  if (items.length && proposalTotal(items) <= 0) issues.push("Итоговая сумма равна нулю.");
  if (!String(draft.client_title || "").trim() && !String(draft.recipient || "").trim()) {
    issues.push("Не указано, кому адресовано КП.");
  }
  return issues;
}
