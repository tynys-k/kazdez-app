export function defaultSections(preset) {
  return {
    risks: { on: preset.risks.length > 0, items: [...preset.risks] },
    advantages: { on: preset.advantages.length > 0, items: preset.advantages.map((a) => ({ ...a })) },
    included: { on: preset.included.length > 0, items: [...preset.included] },
    documents: { on: preset.documents.length > 0, items: [...preset.documents] },
    guarantees: { on: preset.guarantees.length > 0, items: [...preset.guarantees] },
    conditions: { on: preset.conditions.length > 0, items: [...preset.conditions] },
    recommendations: { on: preset.recommendations.length > 0, items: [...preset.recommendations] },
    licenses: { on: true, items: [] },
    signature: { on: preset.style === "official", items: [] },
    cta: { on: !!preset.cta.title, title: preset.cta.title, text: preset.cta.text },
  };
}

export function blankProposal(seed = {}) {
  const preset = segmentPreset(seed.segment || "custom");
  return {
    segment: preset.code,
    style: seed.style || preset.style,
    issue_date: seed.issue_date || new Date().toLocaleDateString("en-CA"),
    branch_code: seed.branch_code || "ALA",
    recipient: preset.recipient,
    client_title: "",
    client_bin: "",
    city: seed.city || "г. Алматы",
    object_label: preset.objectLabel,
    object_address: "",
    object_area: "",
    subject: preset.subject,
    intro: preset.intro,
    items: preset.items.map((item) => blankItem(item)),
    sections: defaultSections(preset),
    validity_days: 30,
    payment_terms: "100% предоплата",
    client_id: null,
    lead_id: null,
    object_id: null,
    status: "draft",
  };
}

// Смена сегмента на заполненной форме. Реквизиты клиента, объект, дата и
// уже введённые цены сохраняются: менеджер меняет сегмент, чтобы получить
// другой текст, а не чтобы потерять работу.
export function applyPreset(draft, segmentCode) {
  const preset = segmentPreset(segmentCode);
  const hadPricedItems = (draft.items || []).some((item) => itemAmount(item) > 0);
  return {
    ...draft,
    segment: preset.code,
    style: preset.style,
    subject: preset.subject,
    recipient: preset.recipient,
    object_label: draft.object_label || preset.objectLabel,
    intro: preset.intro,
    items: hadPricedItems ? draft.items : preset.items.map((item) => blankItem(item)),
    sections: defaultSections(preset),
  };
}

