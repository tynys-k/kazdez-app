export function proposalCompany(settings = {}) {
  const pick = (key) => {
    const value = settings[key];
    return value === null || value === undefined || String(value).trim() === ""
      ? COMPANY_FALLBACK[key]
      : String(value).trim();
  };
  return Object.keys(COMPANY_FALLBACK).reduce((acc, key) => ({ ...acc, [key]: pick(key) }), {});
}

