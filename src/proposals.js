export function prefillFromClient(draft, client, contacts = []) {
  if (!client) return draft;
  const contact = contacts.find((c) => c.client_id === client.id && String(c.name || "").trim());
  const legal = String(client.legal_name || "").trim();
  const isCompany = client.client_type === "company" || !!legal;
  return {
    ...draft,
    client_id: client.id,
    client_title: legal || String(client.name || "").trim(),
    client_bin: String(client.bin_iin || "").trim(),
    // Обращение по имени работает лучше безличного «Уважаемый клиент»,
    // но подставляем его только когда имя действительно известно.
    recipient: contact?.name
      ? `${contact.role ? `${contact.role}, ` : ""}${contact.name}`
      : (isCompany ? `Руководителю ${legal || client.name || "организации"}` : draft.recipient),
  };
}

export function prefillFromObject(draft, object) {
  if (!object) return draft;
  const raw = object.area === null || object.area === undefined ? "" : String(object.area);
  const label = formatArea(raw) ? `${formatArea(raw)} м²` : "";
  return {
    ...draft,
    object_id: object.id,
    object_address: String(object.address || "").trim(),
    object_area: raw,
    object_label: draft.object_label || OBJECT_KIND_LABELS[object.kind] || "",
    items: (draft.items || []).map((item) => (item.volume ? item : { ...item, volume: label })),
  };
}

