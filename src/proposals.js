// ── Строки стоимости ─────────────────────────────────────────────────
//
// Две формы записи, обе встречаются в наших КП:
//   flat — сумма названа целиком: «Дератизация, 3 900 м² — 105 000 ₸»;
//   unit — сумма считается: «16 контейнеров × 3 000 ₸», «4 412 м² × 30 ₸ × 4 раза».
// Считать всегда по unit нельзя: в половине КП цена за м² не раскрывается
// клиенту специально.

export function blankItem(seed = {}) {
  return {
    id: seed.id || (globalThis.crypto?.randomUUID ? crypto.randomUUID() : `i${Math.random().toString(36).slice(2)}`),
    name: seed.name || "",
    note: seed.note || "",
    mode: seed.mode || "flat",
    volume: seed.volume || "",      // подпись объёма: «3 900 м²», «16 шт»
    unit: seed.unit || "",          // ед. изм. для официального стиля
    qty: seed.qty ?? "",
    unit_price: seed.unit_price ?? "",
    times: seed.times ?? 1,         // кратность обработок в год
    amount: seed.amount ?? "",
  };
}

// Площадь по-русски: «4412.25» → «4 412,25». Живёт здесь, а не в вёрстке:
// подпись объёма в строке стоимости заполняется ещё в форме, и там площадь
// должна выглядеть так же, как потом в документе.
export function formatArea(value) {
  const parsed = Number(String(value ?? "").replace(",", "."));
  if (!Number.isFinite(parsed) || parsed <= 0) return "";
  const [whole, fraction] = parsed.toFixed(2).replace(/\.00$/, "").split(".");
  const spaced = whole.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  return fraction ? `${spaced},${fraction}` : spaced;
}

const num = (value) => {
  const parsed = Number(String(value ?? "").replace(/\s/g, "").replace(",", "."));
  return Number.isFinite(parsed) ? parsed : 0;
};

// Сумма одной обработки: нужна отдельно от годовой, потому что в КП для
// госзаказчика печатаются обе, и годовая без неё непроверяема.
export function itemPerTreatment(item = {}) {
  if (item.mode === "unit") return num(item.qty) * num(item.unit_price);
  const times = Math.max(1, num(item.times) || 1);
  return num(item.amount) / times;
}

export function itemAmount(item = {}) {
  if (item.mode === "unit") {
    return num(item.qty) * num(item.unit_price) * Math.max(1, num(item.times) || 1);
  }
  return num(item.amount);
}

export function proposalTotal(items = []) {
  return items.reduce((sum, item) => sum + itemAmount(item), 0);
}

