// Цена из прайса по виду работ и площади. Прайс — это цена компании, и
// подставлять её надо молча, но с пометкой «ориентир», когда площадь не
// названа: иначе КП уйдёт с ценой от нижней ступени как с точной.
export function suggestPrice(pest, area, priceList = []) {
  const hit = priceFor(canonicalPestName(pest), Number(area), priceList);
  if (!hit) return null;
  return { price: Number(hit.price) || 0, exact: hit.exact !== false, row: hit.row };
}

export function applyPriceSuggestion(item, pest, areaValue, priceList = []) {
  const hit = suggestPrice(pest, areaValue, priceList);
  if (!hit) return item;
  const label = formatArea(areaValue) ? `${formatArea(areaValue)} м²` : "";
  return { ...item, mode: "flat", amount: String(hit.price), volume: item.volume || label };
}

// ── Номер и срок ─────────────────────────────────────────────────────

export function proposalNumber(year, branchCode, seq) {
  return `КП-${year}-№${seq}-${String(branchCode || "ALA").toUpperCase()}`;
}

// Номер, который база выдаст следующим. Показывается в форме до сохранения,
// чтобы менеджер видел, под каким номером уйдёт КП. База всё равно выдаёт
// свой: при одновременном создании двух КП здесь будет промах на единицу.
export function nextProposalNumber(proposals = [], year, branchCode = "ALA") {
  const code = String(branchCode).toUpperCase();
  const last = proposals
    .filter((p) => Number(p.year) === Number(year) && String(p.branch_code).toUpperCase() === code)
    .reduce((max, p) => Math.max(max, Number(p.seq) || 0), 0);
  return proposalNumber(year, code, last + 1);
}

export function validUntil(issueDate, days = 30) {
  const base = new Date(`${issueDate}T00:00:00`);
  if (Number.isNaN(base.getTime())) return "";
  base.setDate(base.getDate() + (Number(days) || 30));
  return base.toLocaleDateString("en-CA");
}

export function isExpired(proposal, today = new Date().toLocaleDateString("en-CA")) {
  if (!proposal?.issue_date) return false;
  if (proposal.status === "accepted" || proposal.status === "declined") return false;
  const until = validUntil(proposal.issue_date, proposal.validity_days);
  return !!until && until < today;
}

